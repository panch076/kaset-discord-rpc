#!/bin/zsh
# Builds the bridge, writes config, installs a LaunchAgent, and prepares the
# extension folder for Kaset.
#
# Usage: ./install.sh <discord-application-id>
set -euo pipefail

ROOT="${0:A:h}"
CLIENT_ID="${1:-}"
PORT="${KASET_DP_PORT:-47321}"
LABEL="com.kaset.discord-presence"
SUPPORT="$HOME/Library/Application Support/KasetDiscordPresence"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
LOG="$HOME/Library/Logs/KasetDiscordPresence.log"

if [[ -z "$CLIENT_ID" ]]; then
  echo "Usage: ./install.sh <discord-application-id>"
  echo "Create one at https://discord.com/developers/applications (name it e.g. \"Kaset\")."
  exit 1
fi
if [[ ! "$CLIENT_ID" =~ '^[0-9]{17,20}$' ]]; then
  echo "That doesn't look like a Discord application ID (17-20 digits)."
  exit 1
fi

mkdir -p "$SUPPORT" "$HOME/Library/LaunchAgents" "$HOME/Library/Logs"

# Reuse an existing token so an already-added extension keeps working.
TOKEN=""
if [[ -f "$SUPPORT/config.json" ]]; then
  TOKEN=$(/usr/bin/plutil -extract token raw -o - "$SUPPORT/config.json" 2>/dev/null || true)
fi
[[ -n "$TOKEN" ]] || TOKEN=$(uuidgen)

echo "Building bridge…"
swiftc -O -o "$SUPPORT/kaset-discord-bridge" "$ROOT/bridge/main.swift"

cat > "$SUPPORT/config.json" <<JSON
{
  "clientId": "$CLIENT_ID",
  "port": $PORT,
  "token": "$TOKEN",
  "clearOnPause": true,
  "statusDisplay": "title",
  "lyrics": true
}
JSON

cat > "$ROOT/extension/config.js" <<JS
// Generated by install.sh — must match the bridge's config.json.
globalThis.KASET_DISCORD_PRESENCE = { port: $PORT, token: "$TOKEN" };
JS

cat > "$PLIST" <<XML
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key><array><string>$SUPPORT/kaset-discord-bridge</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ProcessType</key><string>Background</string>
  <key>StandardErrorPath</key><string>$LOG</string>
  <key>StandardOutPath</key><string>$LOG</string>
</dict>
</plist>
XML

launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"

echo
echo "Bridge installed and running (log: $LOG)."
echo
echo "Next, add the extension to Kaset:"
echo "  1. Kaset → Settings (⌘,) → Extensions → +"
echo "  2. Choose: $ROOT/extension"
echo "  3. Restart Kaset."
